// Regenerates src/kern-table.ts: ASCII kerning pairs (GPOS "kern") of a font, in 1/1000 em.
//   node scripts/extract-noto-metrics.mjs path/to/NotoSansJP-Regular.ttf > src/kern-table.ts
import * as fk from "fontkit";
const fontkit = fk.default ?? fk;
const f = fontkit.openSync(process.argv[2]);
const upm = f.unitsPerEm;
const pairs = [];
for (let a = 0x21; a < 0x7f; a++)
  for (let b = 0x21; b < 0x7f; b++) {
    const s = String.fromCharCode(a, b);
    const k = f.layout(s, ["kern"]).positions.reduce((x, p) => x + p.xAdvance, 0) - f.glyphForCodePoint(a).advanceWidth - f.glyphForCodePoint(b).advanceWidth;
    if (k) pairs.push(`${s}${Math.round((k * 1000) / upm)}`);
  }
console.log(`// Generated by scripts/extract-noto-metrics.mjs from ${process.argv[2].split("/").pop()} — do not edit.
// ASCII kerning pairs in 1/1000 em, encoded as "<pair><value>" separated by spaces.
export const KERN_PAIRS = ${JSON.stringify(pairs.join(" "))};`);
